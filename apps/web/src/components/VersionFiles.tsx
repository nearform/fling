/**
 * The files in one version of a site: path, size and type, with a warning when there is no root
 * index.html (the root URL 404s — the most common "why is my link broken?"). Paths link to the
 * live file only for the version being served (`siteUrl` set); older versions aren't served.
 */
import { ExclamationTriangleIcon } from '@heroicons/react/24/outline'
import { useVersionFiles } from '../hooks/queries'
import { errorMessage } from '../lib/api'
import { fileUrl, hasRootIndex, sortForDisplay, splitPath } from '../lib/files'
import { formatBytes } from '../lib/format'

export function VersionFiles({
  name,
  versionId,
  siteUrl,
}: {
  name: string
  versionId: string
  /** set for the served version: paths become links to the live files */
  siteUrl?: string
}) {
  const query = useVersionFiles(name, versionId, true)

  if (query.isPending) {
    return (
      <div className="py-3 text-center">
        <span className="loading loading-spinner loading-sm text-muted" />
      </div>
    )
  }
  if (query.isError) return <p className="text-sm text-error">{errorMessage(query.error)}</p>

  const { files, totalBytes, generatedIndex } = query.data
  const count = `${files.length} file${files.length === 1 ? '' : 's'}`

  return (
    <div className="surface-inset overflow-x-auto">
      <div className="flex flex-wrap items-center gap-2 px-3 pt-2.5 text-xs text-secondary">
        <span>
          {count} · {formatBytes(totalBytes)}
        </span>
        {!hasRootIndex(files) && (
          <span
            className="badge badge-sm tone-warning gap-1"
            title="The site's root URL has no page to serve. Each file still works at its own path."
          >
            <ExclamationTriangleIcon className="h-3 w-3" />
            Root will 404 — no index.html
          </span>
        )}
        {generatedIndex && (
          <span
            className="badge badge-sm badge-ghost"
            title='index.html was generated by "List HTML files" and links every HTML page'
          >
            Generated index
          </span>
        )}
      </div>
      <table className="table table-sm">
        <thead>
          <tr>
            <th>Path</th>
            <th className="text-right">Size</th>
            <th>Type</th>
          </tr>
        </thead>
        <tbody>
          {sortForDisplay(files).map(file => {
            const { folder, name: base } = splitPath(file.path)
            const label = (
              <>
                {folder && <span className="text-muted">{folder}</span>}
                {base}
              </>
            )
            return (
              <tr key={file.path}>
                <td className="font-mono text-xs break-all">
                  {siteUrl ? (
                    <a
                      href={fileUrl(siteUrl, file.path)}
                      target="_blank"
                      rel="noreferrer"
                      className="link link-hover"
                    >
                      {label}
                    </a>
                  ) : (
                    label
                  )}
                </td>
                <td className="text-right tabular-nums whitespace-nowrap">
                  {formatBytes(file.size)}
                </td>
                <td className="text-xs text-muted whitespace-nowrap">{file.contentType}</td>
              </tr>
            )
          })}
        </tbody>
      </table>
    </div>
  )
}
