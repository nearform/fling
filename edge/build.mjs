// Builds the CloudFront Functions, each bundled with what it imports of @fling/shared into one
// script that deploy.yml publishes:
//   - the site router (viewer-request, every behaviour): src/cloudfront.js, the shell around the
//     shared routing decision (@fling/shared/site-routing), into dist/site-router.js, published
//     after filling `__APP_ORIGIN__` and `__SITE_SCHEME__`;
//   - the server status (viewer-response, /api/* with site servers on): src/server-status.js, into
//     dist/server-status.js, which puts a site server's own 403 or 404 back.
//
// cloudfront-js-2.0 is ES5.1 plus a few later features, so the bundle is built twice: as written
// (esnext) and with every feature that runtime lacks marked unsupported. Had esbuild needed to
// rewrite anything for the second, the two differ and the build fails: the source must be written
// in the subset, never silently transpiled into helpers the runtime may not have.
//
// The function is then minified, for room under CloudFront's 10 KB limit: whitespace and local
// names only. esbuild's syntax minification is left off, as it restructures code (an `if` into
// `&&`, statements into one expression) and could put an `await` where the runtime refuses it.
// The body is minified as a script, where top-level declarations are globals that keep their
// names, so it is wrapped in a function first and only `handler` (which CloudFront calls) stays
// at the top level; `cf` and `crypto`, the imports, are globals inside it. Every check runs on both forms, and the
// readable one is written beside the deployable one (dist/<name>.readable.js) to read
// CloudFront's errors against.
import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { buildSync, transformSync } from 'esbuild'

const root = fileURLToPath(new URL('.', import.meta.url))
export const SITE_ROUTER_DIST = `${root}dist/site-router.js`
export const SITE_ROUTER_READABLE_DIST = `${root}dist/site-router.readable.js`
export const SERVER_STATUS_DIST = `${root}dist/server-status.js`
export const SERVER_STATUS_READABLE_DIST = `${root}dist/server-status.readable.js`

/** Each function: its source, what it is called in errors, and its generated header. */
const FUNCTIONS = {
  siteRouter: {
    entry: 'cloudfront.js',
    label: 'site-router',
    header:
      '// Generated by edge/build.mjs from edge/src/cloudfront.js and @fling/shared/site-routing. Do not edit.',
  },
  serverStatus: {
    entry: 'server-status.js',
    label: 'server-status',
    header:
      '// Generated by edge/build.mjs from edge/src/server-status.js and @fling/shared/route-keys. Do not edit.',
  },
}

/** Syntax cloudfront-js-2.0 does not have (esbuild feature names). */
const UNSUPPORTED = [
  'array-spread',
  'async-generator',
  'bigint',
  'class',
  'class-field',
  'class-private-field',
  'class-private-method',
  'class-static-field',
  'default-argument',
  'destructuring',
  'for-await',
  'for-of',
  'generator',
  'logical-assignment',
  'nested-rest-binding',
  'nullish-coalescing',
  'object-rest-spread',
  'optional-catch-binding',
  'optional-chain',
  'top-level-await',
]

function bundle(entry, supported) {
  const out = buildSync({
    entryPoints: [`${root}src/${entry}`],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'esnext',
    supported,
    external: ['cloudfront', 'crypto'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  })
  return out.outputFiles[0].text
}

const RESTRICTED = Object.fromEntries(UNSUPPORTED.map(f => [f, false]))
/**
 * CloudFront Functions take at most 10 KB of code. Fail the build with room to spare, rather than
 * the deploy's `update-function`.
 */
export const SITE_ROUTER_MAX_BYTES = 9800
/** The same budget for every CloudFront Function this builds. */
export const EDGE_FUNCTION_MAX_BYTES = SITE_ROUTER_MAX_BYTES
const LACKS = 'the source uses syntax cloudfront-js-2.0 lacks (see UNSUPPORTED in edge/build.mjs)'

function minify(body, supported) {
  return transformSync(body, {
    minifyWhitespace: true,
    minifyIdentifiers: true,
    target: 'esnext',
    supported,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  }).code.trimEnd()
}

/** Fails unless `code` keeps to what cloudfront-js-2.0 accepts of async and await. */
function checkAwaits(code, label) {
  // "async arguments and closures are not supported": only async function declarations.
  if (/async\s*(\(|[A-Za-z_$][\w$]*\s*=>|function\s*\()/.test(code)) {
    throw new Error(
      `${label}: async arrow functions and async function expressions are not supported`
    )
  }
  // "await in arguments not supported" (and nested in other expressions): only `await f()` as a
  // statement, `return await f()`, or the whole right-hand side of `x = await f()`.
  for (const line of code.split('\n')) {
    for (const m of line.matchAll(/\bawait\b/g)) {
      const before = line.slice(0, m.index).trim()
      if (!/(^|[;{}]|\breturn|(^|[;{})]|\b(const|let|var))\s*[\w$.]+\s*=)$/.test(before)) {
        throw new Error(`${label}: await must be a whole statement or assignment: ${line.trim()}`)
      }
    }
  }
}

function buildReadable({ entry, label, header }) {
  const plain = bundle(entry, {})
  if (plain !== bundle(entry, RESTRICTED)) throw new Error(`${label}: ${LACKS}`)
  const exportLine = /^export\s*\{\s*handler\s*\};?\s*$/m
  if (!exportLine.test(plain)) throw new Error(`${label}: expected \`export { handler }\``)
  const code = plain.replace(exportLine, '').trimEnd()
  if (/^export\s/m.test(code)) throw new Error(`${label}: unexpected export`)
  checkAwaits(code, label)
  return `${header}\n${code}\n`
}

function buildDeployable(fn) {
  const { label, header } = fn
  const readable = buildReadable(fn)
  const importLine = /^import \w+ from "\w+";$/gm
  const imports = readable.match(importLine) ?? []
  const body = `var edgeFunction = (function () {\n${readable.replace(importLine, '')}\nreturn handler\n})()\nasync function handler(event) {\n  return await edgeFunction(event)\n}\n`
  const code = minify(body, {})
  if (code !== minify(body, RESTRICTED)) throw new Error(`${label}: minified, ${LACKS}`)
  if (!/(^|[;}])async function handler\(/.test(code)) {
    throw new Error(`${label}: minifying renamed \`handler\``)
  }
  checkAwaits(code, label)
  const out = `${header}\n${imports.join('\n')}${imports.length ? '\n' : ''}${code}\n`
  const bytes = Buffer.byteLength(out)
  if (bytes > EDGE_FUNCTION_MAX_BYTES) {
    throw new Error(
      `${label}: ${bytes} bytes, over ${EDGE_FUNCTION_MAX_BYTES} (CloudFront takes 10 KB)`
    )
  }
  return out
}

/** The site router as bundled, before minifying (placeholders still in). */
export const buildReadableSiteRouter = () => buildReadable(FUNCTIONS.siteRouter)
/** The deployable site router, minified (placeholders still in). */
export const buildSiteRouter = () => buildDeployable(FUNCTIONS.siteRouter)
/** The server status function as bundled, before minifying. */
export const buildReadableServerStatus = () => buildReadable(FUNCTIONS.serverStatus)
/** The deployable server status function, minified. */
export const buildServerStatus = () => buildDeployable(FUNCTIONS.serverStatus)

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(`${root}dist`, { recursive: true })
  for (const [readable, deployable, dist, readableDist] of [
    [buildReadableSiteRouter, buildSiteRouter, SITE_ROUTER_DIST, SITE_ROUTER_READABLE_DIST],
    [buildReadableServerStatus, buildServerStatus, SERVER_STATUS_DIST, SERVER_STATUS_READABLE_DIST],
  ]) {
    writeFileSync(readableDist, readable())
    const code = deployable()
    writeFileSync(dist, code)
    console.log(`wrote dist/${dist.split('/').pop()} (${Buffer.byteLength(code)} bytes)`)
  }
}
