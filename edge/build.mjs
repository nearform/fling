// Builds the CloudFront Function: src/cloudfront.js (the shell) bundled with the shared routing
// decision (@fling/shared/site-routing) into one script, dist/site-router.js, which deploy.yml
// publishes after filling `__APP_ORIGIN__` and `__SITE_SCHEME__`.
//
// cloudfront-js-2.0 is ES5.1 plus a few later features, so the bundle is built twice: as written
// (esnext) and with every feature that runtime lacks marked unsupported. Had esbuild needed to
// rewrite anything for the second, the two differ and the build fails: the source must be written
// in the subset, never silently transpiled into helpers the runtime may not have.
//
// The function is then minified, for room under CloudFront's 10 KB limit: whitespace and local
// names only. esbuild's syntax minification is left off, as it restructures code (an `if` into
// `&&`, statements into one expression) and could put an `await` where the runtime refuses it.
// The imports and `handler` keep their names: the body is minified as a script, where `cf`,
// `crypto` and top-level declarations are globals. Every check runs on both forms, and the
// readable one is written beside the deployable one (dist/site-router.readable.js) to read
// CloudFront's errors against.
import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { buildSync, transformSync } from 'esbuild'

const root = fileURLToPath(new URL('.', import.meta.url))
export const SITE_ROUTER_DIST = `${root}dist/site-router.js`
export const SITE_ROUTER_READABLE_DIST = `${root}dist/site-router.readable.js`
const HEADER =
  '// Generated by edge/build.mjs from edge/src/cloudfront.js and @fling/shared/site-routing. Do not edit.'

/** Syntax cloudfront-js-2.0 does not have (esbuild feature names). */
const UNSUPPORTED = [
  'array-spread',
  'async-generator',
  'bigint',
  'class',
  'class-field',
  'class-private-field',
  'class-private-method',
  'class-static-field',
  'default-argument',
  'destructuring',
  'for-await',
  'for-of',
  'generator',
  'logical-assignment',
  'nested-rest-binding',
  'nullish-coalescing',
  'object-rest-spread',
  'optional-catch-binding',
  'optional-chain',
  'top-level-await',
]

function bundle(supported) {
  const out = buildSync({
    entryPoints: [`${root}src/cloudfront.js`],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'esnext',
    supported,
    external: ['cloudfront', 'crypto'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  })
  return out.outputFiles[0].text
}

const RESTRICTED = Object.fromEntries(UNSUPPORTED.map(f => [f, false]))
const LACKS = 'the source uses syntax cloudfront-js-2.0 lacks (see UNSUPPORTED in edge/build.mjs)'

function minify(body, supported) {
  return transformSync(body, {
    minifyWhitespace: true,
    minifyIdentifiers: true,
    target: 'esnext',
    supported,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  }).code.trimEnd()
}

/** Fails unless `code` keeps to what cloudfront-js-2.0 accepts of async and await. */
function checkAwaits(code) {
  // "async arguments and closures are not supported": only async function declarations.
  if (/async\s*(\(|[A-Za-z_$][\w$]*\s*=>|function\s*\()/.test(code)) {
    throw new Error(
      'site-router: async arrow functions and async function expressions are not supported'
    )
  }
  // "await in arguments not supported" (and nested in other expressions): only `await f()` as a
  // statement, `return await f()`, or the whole right-hand side of `x = await f()`.
  for (const line of code.split('\n')) {
    for (const m of line.matchAll(/\bawait\b/g)) {
      const before = line.slice(0, m.index).trim()
      if (!/(^|[;{}]|\breturn|(^|[;{})]|\b(const|let|var))\s*[\w$.]+\s*=)$/.test(before)) {
        throw new Error(
          `site-router: await must be a whole statement or assignment: ${line.trim()}`
        )
      }
    }
  }
}

/** The CloudFront Function as bundled, before minifying (placeholders still in). */
export function buildReadableSiteRouter() {
  const plain = bundle({})
  if (plain !== bundle(RESTRICTED)) throw new Error(`site-router: ${LACKS}`)
  const exportLine = /^export\s*\{\s*handler\s*\};?\s*$/m
  if (!exportLine.test(plain)) throw new Error('site-router: expected `export { handler }`')
  const code = plain.replace(exportLine, '').trimEnd()
  if (/^export\s/m.test(code)) throw new Error('site-router: unexpected export')
  checkAwaits(code)
  return `${HEADER}\n${code}\n`
}

/** The deployable CloudFront Function source, minified (placeholders still in). */
export function buildSiteRouter() {
  const readable = buildReadableSiteRouter()
  const importLine = /^import \w+ from "\w+";$/gm
  const imports = readable.match(importLine) ?? []
  const body = readable.replace(importLine, '')
  const code = minify(body, {})
  if (code !== minify(body, RESTRICTED)) throw new Error(`site-router: minified, ${LACKS}`)
  if (!/(^|[;}])async function handler\(/.test(code)) {
    throw new Error('site-router: minifying renamed `handler`')
  }
  checkAwaits(code)
  return `${HEADER}\n${imports.join('\n')}\n${code}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(`${root}dist`, { recursive: true })
  writeFileSync(SITE_ROUTER_READABLE_DIST, buildReadableSiteRouter())
  const code = buildSiteRouter()
  writeFileSync(SITE_ROUTER_DIST, code)
  console.log(`wrote dist/site-router.js (${Buffer.byteLength(code)} bytes)`)
}
