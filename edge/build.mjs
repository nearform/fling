// Builds the CloudFront Function: src/cloudfront.js (the shell) bundled with the shared routing
// decision (@fling/shared/site-routing) into one script, dist/site-router.js, which deploy.yml
// publishes after filling `__APP_ORIGIN__` and `__SITE_SCHEME__`.
//
// cloudfront-js-2.0 is ES5.1 plus a few later features, so the bundle is built twice: as written
// (esnext) and with every feature that runtime lacks marked unsupported. Had esbuild needed to
// rewrite anything for the second, the two differ and the build fails: the source must be written
// in the subset, never silently transpiled into helpers the runtime may not have.
import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { buildSync } from 'esbuild'

const root = fileURLToPath(new URL('.', import.meta.url))
export const SITE_ROUTER_DIST = `${root}dist/site-router.js`

/** Syntax cloudfront-js-2.0 does not have (esbuild feature names). */
const UNSUPPORTED = [
  'array-spread',
  'async-generator',
  'bigint',
  'class',
  'class-field',
  'class-private-field',
  'class-private-method',
  'class-static-field',
  'default-argument',
  'destructuring',
  'for-await',
  'for-of',
  'generator',
  'logical-assignment',
  'nested-rest-binding',
  'nullish-coalescing',
  'object-rest-spread',
  'optional-catch-binding',
  'optional-chain',
  'top-level-await',
]

function bundle(supported) {
  const out = buildSync({
    entryPoints: [`${root}src/cloudfront.js`],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'esnext',
    supported,
    external: ['cloudfront', 'crypto'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  })
  return out.outputFiles[0].text
}

/** The deployable CloudFront Function source (placeholders still in). */
export function buildSiteRouter() {
  const plain = bundle({})
  const restricted = bundle(Object.fromEntries(UNSUPPORTED.map(f => [f, false])))
  if (plain !== restricted) {
    throw new Error(
      'site-router: the source uses syntax cloudfront-js-2.0 lacks (see UNSUPPORTED in edge/build.mjs)'
    )
  }
  const exportLine = /^export\s*\{\s*handler\s*\};?\s*$/m
  if (!exportLine.test(plain)) throw new Error('site-router: expected `export { handler }`')
  const code = plain.replace(exportLine, '').trimEnd()
  if (/^export\s/m.test(code)) throw new Error('site-router: unexpected export')
  // "async arguments and closures are not supported": only async function declarations.
  if (/async\s*(\(|[A-Za-z_$][\w$]*\s*=>|function\s*\()/.test(code)) {
    throw new Error(
      'site-router: async arrow functions and async function expressions are not supported'
    )
  }
  return `// Generated by edge/build.mjs from edge/src/cloudfront.js and @fling/shared/site-routing. Do not edit.\n${code}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = buildSiteRouter()
  mkdirSync(`${root}dist`, { recursive: true })
  writeFileSync(SITE_ROUTER_DIST, code)
  console.log(`wrote dist/site-router.js (${Buffer.byteLength(code)} bytes)`)
}
